export function useTranslation(lang = "es") {
  const t = (key, replacements = {}) => {
    let text = translations[lang]?.[key] || translations.es[key] || key;
    Object.entries(replacements).forEach(([k, v]) => {
      text = text.replace(`{{${k}}}`, v);
    });
    return text;
  };
  return t;
}
